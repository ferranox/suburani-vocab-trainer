#!/usr/bin/env node
/*
 * Generates data/vocab.js from tools/appendix-a.txt.
 * Usage: node tools/build-vocab.js
 *
 * Line format in the appendix:
 *   Latin entry :: English meaning(s)
 *   Latin entry :: English meaning(s) :: accept=alt1 | alt2
 * "# Chapter N" starts a chapter; lines starting with "##" / "###" or "```" are ignored.
 */
'use strict';
var fs = require('fs');
var path = require('path');

var SRC = path.join(__dirname, 'appendix-a.txt');
var OUT = path.join(__dirname, '..', 'data', 'vocab.js');

function bookFor(chapter) {
  if (chapter <= 16) return 1;
  if (chapter <= 32) return 2;
  return 3;
}

var text = fs.readFileSync(SRC, 'utf8').normalize('NFC');
var lines = text.split(/\r?\n/);
var entries = [];
var chapter = 0;
var indexInChapter = 0;
var errors = [];

lines.forEach(function (raw, lineNo) {
  var line = raw.trim();
  if (!line || line.indexOf('```') === 0 || /^#{2,}/.test(line)) return;
  var m = /^#\s*Chapter\s+(\d+)\s*$/i.exec(line);
  if (m) {
    chapter = parseInt(m[1], 10);
    indexInChapter = 0;
    return;
  }
  if (!chapter) { errors.push('Line ' + (lineNo + 1) + ': entry before first chapter'); return; }
  var parts = line.split(' :: ');
  if (parts.length < 2 || parts.length > 3) {
    errors.push('Line ' + (lineNo + 1) + ': cannot parse "' + line + '"');
    return;
  }
  var latin = parts[0].trim();
  var english = parts[1].trim();
  var accept = [];
  if (parts[2]) {
    var a = /^accept=(.*)$/.exec(parts[2].trim());
    if (!a) { errors.push('Line ' + (lineNo + 1) + ': bad third field "' + parts[2] + '"'); return; }
    accept = a[1].split('|').map(function (s) { return s.trim(); }).filter(Boolean);
  }
  indexInChapter++;
  entries.push({
    id: chapter + '-' + indexInChapter,
    book: bookFor(chapter),
    chapter: chapter,
    latin: latin,
    english: english,
    accept: accept
  });
});

// ---- Verification -------------------------------------------------------
var perChapter = {};
entries.forEach(function (e) {
  perChapter[e.chapter] = (perChapter[e.chapter] || 0) + 1;
  if (!e.latin || !e.english) errors.push('Empty field in ' + e.id);
});
for (var c = 1; c <= 40; c++) {
  if (perChapter[c] !== 20) errors.push('Chapter ' + c + ' has ' + (perChapter[c] || 0) + ' entries (expected 20)');
}
if (Object.keys(perChapter).length !== 40) errors.push('Expected 40 chapters, found ' + Object.keys(perChapter).length);
if (entries.length !== 800) errors.push('Expected 800 entries, found ' + entries.length);

if (errors.length) {
  console.error('vocab build FAILED:\n  ' + errors.join('\n  '));
  process.exit(1);
}

var body = entries.map(function (e) { return '  ' + JSON.stringify(e); }).join(',\n');
var out =
  '/* GENERATED by tools/build-vocab.js from tools/appendix-a.txt – do not edit by hand. */\n' +
  '/* 40 chapters × 20 words = 800 entries. */\n' +
  '(function (root) {\n' +
  '  var VOCAB = [\n' + body + '\n  ];\n' +
  '  root.VOCAB = VOCAB;\n' +
  "  if (typeof module !== 'undefined' && module.exports) module.exports = VOCAB;\n" +
  "})(typeof window !== 'undefined' ? window : this);\n";

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log('Wrote ' + entries.length + ' entries in ' + Object.keys(perChapter).length + ' chapters to ' + path.relative(process.cwd(), OUT));
